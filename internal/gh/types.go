package gh

import (
	"strings"
	"time"
)

// User is a GitHub account.
type User struct {
	Login string `json:"login"`
	Type  string `json:"type"`
}

// Repo is a repository the user can see.
type Repo struct {
	ID            int64     `json:"id"`
	Name          string    `json:"name"`
	FullName      string    `json:"full_name"`
	Owner         User      `json:"owner"`
	Private       bool      `json:"private"`
	Archived      bool      `json:"archived"`
	Fork          bool      `json:"fork"`
	Stars         int       `json:"stargazers_count"`
	DefaultBranch string    `json:"default_branch"`
	HTMLURL       string    `json:"html_url"`
	PushedAt      time.Time `json:"pushed_at"`
	UpdatedAt     time.Time `json:"updated_at"`
	// HasActions and Health come from SweepRepos: whether the repo has
	// workflow files, and the check state of the last commits on its default
	// branch, newest first ("SUCCESS", "FAILURE", "PENDING", … or "" for none).
	HasActions bool `json:"has_actions,omitempty"`
	// Permission is your role in the repo: ADMIN, MAINTAIN, WRITE, TRIAGE or READ.
	Permission string `json:"permission,omitempty"`
	Perms      *struct {
		Admin    bool `json:"admin"`
		Maintain bool `json:"maintain"`
		Push     bool `json:"push"`
		Triage   bool `json:"triage"`
		Pull     bool `json:"pull"`
	} `json:"permissions,omitempty"`
	Health []string `json:"health,omitempty"`
	// IssuesOff says the repo has issues turned off; SweepRepos reads it.
	IssuesOff bool `json:"issues_off,omitempty"`
}

// Workflow is a workflow definition in a repository.
type Workflow struct {
	ID      int64  `json:"id"`
	Name    string `json:"name"`
	Path    string `json:"path"`
	State   string `json:"state"`
	HTMLURL string `json:"html_url"`
}

// Dynamic reports whether the workflow is generated by GitHub (Pages, Dependabot…)
// rather than backed by a YAML file in the repository.
func (w Workflow) Dynamic() bool { return len(w.Path) > 8 && w.Path[:8] == "dynamic/" }

// Run is a single workflow run.
type Run struct {
	ID int64 `json:"id"`
	// NodeID is the GraphQL id. A run list cached before it was read lacks it
	// until the list changes.
	NodeID          string    `json:"node_id,omitempty"`
	Name            string    `json:"name"`
	DisplayTitle    string    `json:"display_title"`
	RunNumber       int       `json:"run_number"`
	RunAttempt      int       `json:"run_attempt"`
	Event           string    `json:"event"`
	Status          string    `json:"status"`
	Conclusion      string    `json:"conclusion"`
	HeadBranch      string    `json:"head_branch"`
	HeadSHA         string    `json:"head_sha"`
	WorkflowID      int64     `json:"workflow_id"`
	HTMLURL         string    `json:"html_url"`
	Path            string    `json:"path"`
	Actor           User      `json:"actor"`
	TriggeringActor User      `json:"triggering_actor"`
	CreatedAt       time.Time `json:"created_at"`
	UpdatedAt       time.Time `json:"updated_at"`
	RunStartedAt    time.Time `json:"run_started_at"`
	PullRequests    []struct {
		Number int `json:"number"`
	} `json:"pull_requests"`
	ReferencedWorkflows []ReferencedWorkflow `json:"referenced_workflows"`
	// Requeued says GitHub called the run queued after it had started: a
	// later job of it waits for a runner. See Client.KeepStarted.
	Requeued bool `json:"-"`
}

// ReferencedWorkflow is a reusable workflow a run called. Path is
// "owner/repo/.github/workflows/file.yml@version".
type ReferencedWorkflow struct {
	Path string `json:"path"`
	SHA  string `json:"sha"`
	Ref  string `json:"ref"`
}

// Split parses Path into the repository the workflow lives in, the file's
// path in it and the version it was called at: a tag, a branch or a commit.
func (w ReferencedWorkflow) Split() (repo, file, version string) {
	at := strings.LastIndex(w.Path, "@")
	where := w.Path
	if at >= 0 {
		where, version = w.Path[:at], w.Path[at+1:]
	}
	parts := strings.SplitN(where, "/", 3)
	if len(parts) < 3 {
		return "", where, version
	}
	return parts[0] + "/" + parts[1], parts[2], version
}

// DependabotUpdate reports whether the run is one of Dependabot's version update jobs.
func (r Run) DependabotUpdate() bool { return strings.HasPrefix(r.Path, "dynamic/dependabot/") }

// Active reports whether the run has not finished yet.
func (r Run) Active() bool { return r.Status != "completed" }

// Duration is the wall-clock time of the run so far.
func (r Run) Duration(now time.Time) time.Duration {
	start := r.RunStartedAt
	if start.IsZero() {
		start = r.CreatedAt
	}
	if r.Active() {
		return now.Sub(start)
	}
	return r.UpdatedAt.Sub(start)
}

// Job is one job of a run, including its steps.
type Job struct {
	ID          int64     `json:"id"`
	RunID       int64     `json:"run_id"`
	Name        string    `json:"name"`
	Status      string    `json:"status"`
	Conclusion  string    `json:"conclusion"`
	StartedAt   time.Time `json:"started_at"`
	CompletedAt time.Time `json:"completed_at"`
	HTMLURL     string    `json:"html_url"`
	CreatedAt   time.Time `json:"created_at"`
	RunnerName  string    `json:"runner_name"`
	// RunnerGroup is "GitHub Actions" for a runner GitHub hosts.
	RunnerGroup string   `json:"runner_group_name"`
	Labels      []string `json:"labels"`
	RunAttempt  int      `json:"run_attempt"`
	Steps       []Step   `json:"steps"`
}

// Duration is how long the job ran (so far).
func (j Job) Duration(now time.Time) time.Duration {
	if j.StartedAt.IsZero() {
		return 0
	}
	if j.CompletedAt.IsZero() || j.Status != "completed" {
		return now.Sub(j.StartedAt)
	}
	return j.CompletedAt.Sub(j.StartedAt)
}

// Queued is how long the job waited for a runner (so far), or 0 when GitHub
// did not say when it was queued.
func (j Job) Queued(now time.Time) time.Duration {
	if j.CreatedAt.IsZero() {
		return 0
	}
	if j.StartedAt.IsZero() || j.StartedAt.Before(j.CreatedAt) {
		if j.Status == "completed" {
			return 0
		}
		return now.Sub(j.CreatedAt)
	}
	return j.StartedAt.Sub(j.CreatedAt)
}

// Step is one step of a job.
type Step struct {
	Name        string    `json:"name"`
	Number      int       `json:"number"`
	Status      string    `json:"status"`
	Conclusion  string    `json:"conclusion"`
	StartedAt   time.Time `json:"started_at"`
	CompletedAt time.Time `json:"completed_at"`
}

// Duration is how long the step ran (so far).
func (s Step) Duration(now time.Time) time.Duration {
	if s.StartedAt.IsZero() {
		return 0
	}
	if s.CompletedAt.IsZero() || s.Status != "completed" {
		return now.Sub(s.StartedAt)
	}
	return s.CompletedAt.Sub(s.StartedAt)
}

// Annotation is a check-run annotation (errors and warnings surfaced by GitHub).
type Annotation struct {
	Path            string `json:"path"`
	StartLine       int    `json:"start_line"`
	AnnotationLevel string `json:"annotation_level"`
	Title           string `json:"title"`
	Message         string `json:"message"`
}

// PendingDeployment is an environment a run is waiting on for approval.
type PendingDeployment struct {
	Environment struct {
		ID   int64  `json:"id"`
		Name string `json:"name"`
	} `json:"environment"`
	WaitTimer             int  `json:"wait_timer"`
	CurrentUserCanApprove bool `json:"current_user_can_approve"`
}

// Rate is the REST API rate-limit state as seen on the last response.
type Rate struct {
	Limit     int
	Remaining int
	Reset     time.Time
	// PausedUntil is set while GitHub has asked us to slow down.
	PausedUntil time.Time
}

// Saving reports whether less than a fifth of the limit is left before it
// resets. Reads are paused then, leaving the rest for other tools on the account.
func (r Rate) Saving(now time.Time) bool {
	return r.Limit > 0 && r.Remaining*5 < r.Limit && now.Before(r.Reset)
}
